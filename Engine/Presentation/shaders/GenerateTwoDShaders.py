#!/usr/bin/env python3
"""Embed native linear 2D entries compiled from the shared Slang library (pinned 2026.18)."""
import argparse
from pathlib import Path
import re
import struct
import subprocess
import tempfile


def generate(compiler: str, check: bool) -> None:
    root = Path(__file__).resolve().parents[3]
    shaders = root / 'Engine/Presentation/shaders'
    version = subprocess.run([compiler, '-v'], check=True, text=True, capture_output=True)
    if not re.search(r'2026\.18(?:\D|$)', version.stdout + version.stderr):
        raise SystemExit('Native linear 2D generation requires Slang 2026.18')
    targets = [('spirv', 'Vulkan'), ('hlsl', 'Hlsl'), ('metal', 'Metal')]
    with tempfile.TemporaryDirectory(prefix='nexora-twod-shaders-') as directory:
        for target, label in targets:
            text = '// Generated by shaders/GenerateTwoDShaders.py with Slang 2026.18.\n'
            text += '// clang-format off\n#pragma once\n#include <cstdint>\nnamespace Nexora::Presentation {\n'
            for stage, entry in [('vert', 'twoDVertexMain'), ('instance', 'twoDInstanceMain'), ('frag', 'twoDFragmentMain'), ('composite', 'twoDCompositeMain')]:
                output = Path(directory) / f'{stage}.{target}'
                command = [compiler, 'Engine/Presentation/shaders/twod_linear.slang', '-I', 'Shaders',
                           '-target', target, '-entry', entry, '-o', str(output)]
                if target == 'spirv':
                    command += ['-profile', 'glsl_450', '-DNEXORA_VULKAN=1']
                elif target == 'hlsl':
                    command += ['-profile', 'sm_5_0']
                subprocess.run(command, cwd=root, check=True)
                name = f'twod_linear_{target}_{stage}'
                if target == 'spirv':
                    data = output.read_bytes()
                    if len(data) % 4 or struct.unpack_from('<I', data)[0] != 0x07230203:
                        raise SystemExit('Invalid generated SPIR-V')
                    words = struct.unpack(f'<{len(data)//4}I', data)
                    text += f'inline constexpr std::uint32_t {name}[] = {{\n'
                    for start in range(0, len(words), 8):
                        text += '  ' + ', '.join(f'0x{x:08x}' for x in words[start:start+8]) + ',\n'
                    text += '};\n'
                else:
                    source = output.read_text(encoding='utf-8')
                    # Source diagnostics are reproducible repository-relative compiler paths.
                    if ')NEXORA_TWOD"' in source:
                        raise SystemExit('Generated source contains the raw-string delimiter')
                    text += f'inline constexpr char {name}[] = R"NEXORA_TWOD(\n{source})NEXORA_TWOD";\n'
            text += '} // namespace Nexora::Presentation\n// clang-format on\n'
            path = root / f'Engine/Presentation/src/TwoDLinear{label}Shaders.h'
            if check:
                if not path.is_file() or path.read_text(encoding='utf-8') != text:
                    if path.is_file():
                        old = path.read_text(encoding='utf-8').splitlines()
                        new = text.splitlines()
                        differences = [(i+1, a, b) for i, (a, b) in enumerate(zip(old, new)) if a != b]
                        print(f'Embedded lines expected={len(old)} actual={len(new)}')
                        for line, expected, actual in differences[:8]:
                            print(f'line {line}: expected {expected} / actual {actual}')
                    raise SystemExit(f'Embedded linear 2D shader differs: {path}')
            else:
                path.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', default='slangc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.compiler, args.check)
