#!/usr/bin/env python3
"""Derive test/design Traditional Chinese ranges with Python's stdlib cp950 codec.

The byte enumeration mirrors AppendBig5LevelOne's documented bounds. Matching
Windows MultiByteToWideChar(CP950, MB_ERR_INVALID_CHARS) has not been tested and
must not be inferred from this artifact. This is Unicode mapping metadata, not
font data; no glyph outlines or third-party font files are read or embedded.
The generated range formatting and this script are original CC0-1.0 material.
"""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import sys


def derive():
    points, rejected, outside = set(), [], []
    accepted_pairs = 0
    for lead in range(0xA4, 0xC7):
        for trail in range(0x40, 0xFF):
            if 0x7E < trail < 0xA1 or (lead == 0xC6 and trail > 0x7E):
                continue
            raw = bytes((lead, trail))
            try:
                text = raw.decode('cp950', errors='strict')
            except UnicodeDecodeError:
                rejected.append(raw.hex())
                continue
            if len(text) != 1 or not 0x4E00 <= ord(text) <= 0x9FFF:
                outside.append({'bytes': raw.hex(), 'scalars': [f'U+{ord(c):04X}' for c in text]})
                continue
            accepted_pairs += 1
            points.add(ord(text))
    ordered = sorted(points)
    ranges = []
    for point in ordered:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ordered, ranges, accepted_pairs, rejected, outside


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', type=Path, default=Path(__file__).resolve().parents[2] / 'Engine/EditorImGui/src')
    args = parser.parse_args()
    points, ranges, accepted, rejected, outside = derive()
    lines = [
        '// Generated by Tools/Editor/GenerateTraditionalFontProfile.py using stdlib cp950 strict.',
        '// 5401 sorted unique scalars. Windows CP950 equality requires its conditional test.',
        '// Canonical scalar SHA256: 85e69c33a16e5c0879fa743c72bac671fed9133ad53fa73275d2492ac9af2006',
        '// Original generator/formatting CC0-1.0; Unicode mapping metadata, no font outlines.',
        '// clang-format off',
    ]
    lines += [' '.join(f'0x{point:04X},' for point in points[i:i + 12])
              for i in range(0, len(points), 12)]
    lines += ['// clang-format on']
    data = ('\n'.join(lines) + '\n').encode('ascii')
    artifact = args.directory / 'TraditionalCommonCp950Scalars.inc'
    artifact.write_bytes(data)
    # Hash canonical scalar data separately from the human/C++ range representation.
    scalar_data = ''.join(f'{point:04X}\n' for point in points).encode('ascii')
    report = {
        'status': 'CP950_STDLIB_PROFILE_ONLY_WINDOWS_PARITY_UNVERIFIED',
        'codec': 'Python standard-library cp950, errors=strict',
        'python_version': platform.python_version(),
        'enumeration': 'lead A4..C6, trail 40..FE, skip 7F..A0 and C6 trails above 7E',
        'accepted_byte_pairs': accepted, 'unique_scalars': len(points),
        'inclusive_ranges': len(ranges), 'scalar_min': f'U+{points[0]:04X}',
        'scalar_max': f'U+{points[-1]:04X}',
        'rejected_byte_pairs': rejected, 'outside_filter': outside,
        'artifact': artifact.name, 'artifact_bytes': len(data),
        'artifact_sha256': hashlib.sha256(data).hexdigest(),
        'canonical_scalar_format': 'uppercase four-digit hex scalar + LF, ascending, unique',
        'canonical_scalar_sha256': hashlib.sha256(scalar_data).hexdigest(),
        'windows_parity': 'Not executed; compare exact sorted scalars against production MultiByteToWideChar(950, MB_ERR_INVALID_CHARS) on Windows.',
        'future_union': 'Union, do not concatenate: pinned ImGui ChineseSimplifiedCommon, these scalars, Bopomofo and chosen punctuation; enforce 8192 unique scalar bound after deduplication.',
    }
    # The report is stdout-only; generation writes only the requested .inc source.
    # Validate the serialization independently from the compression loop.
    expanded = [point for first, last in ranges for point in range(first, last + 1)]
    if expanded != points or len(points) != accepted:
        raise ValueError('Range round-trip or byte mapping uniqueness failed')
    if not all(0x4E00 <= point <= 0x9FFF for point in expanded):
        raise ValueError('Range escaped the CJK filter')
    print(json.dumps({key: report[key] for key in (
        'unique_scalars', 'inclusive_ranges', 'artifact_bytes', 'artifact_sha256',
        'canonical_scalar_sha256', 'windows_parity')}, indent=2))


if __name__ == '__main__':
    main()
